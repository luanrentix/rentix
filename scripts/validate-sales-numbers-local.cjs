const assert = require('node:assert/strict');
const fs = require('node:fs');
const ts = require('typescript');
const loaded = { exports: {} };
new Function('module', 'exports', ts.transpileModule(fs.readFileSync('services/sales-numbers.ts', 'utf8'), { compilerOptions: { module: ts.ModuleKind.CommonJS, target: ts.ScriptTarget.ES2020 } }).outputText)(loaded, loaded.exports);
const { quantityAmount, addQuantity, saleLineCents, saleSubtotal, saleReturnCents, saleAdjustmentCents } = loaded.exports;
const { allocateSaleAdjustment } = loaded.exports;
const { adjustmentForSaleTotal } = loaded.exports;
assert.deepEqual(adjustmentForSaleTotal(208.99, 200, 109.99, true), { discount: 8.99, addition: 0 });
assert.deepEqual(adjustmentForSaleTotal(208.99, 220, 109.99, true), { discount: 0, addition: 11.01 });
assert.deepEqual(adjustmentForSaleTotal(208.99, 208.99, 109.99, true), { discount: 0, addition: 0 });
assert.throws(() => adjustmentForSaleTotal(208.99, 90, 109.99, true));
assert.throws(() => adjustmentForSaleTotal(100, 101, 100, false));
assert.throws(() => adjustmentForSaleTotal(100, -1, 100, true));
assert.throws(() => adjustmentForSaleTotal(100, NaN, 100, true));
assert.deepEqual(allocateSaleAdjustment(30, [10000, 20000, 0]), [1000, 2000, 0]);
assert.deepEqual(allocateSaleAdjustment(0.01, [100, 100, 100]), [1, 0, 0]);
assert.deepEqual(allocateSaleAdjustment(0.02, [1, 1, 1]), [1, 1, 0]);
assert.deepEqual(allocateSaleAdjustment(1, [0, 0]), [0, 0]);
assert.deepEqual(allocateSaleAdjustment(0, [100]), [0]);
assert.equal(saleLineCents(0.75, 2.9), 218);
assert.equal(saleLineCents(0.01, 0.5), 1);
assert.equal(saleLineCents(2.15, 1), 215);
assert.deepEqual(saleAdjustmentCents({ quantity: 0.5, originalUnitPrice: 0.02, baseUnitPrice: 0.02, discount: 0.01, unitPrice: 0.01 }), { discount: 0, addition: 0, promotion: 0 });
assert.deepEqual(saleAdjustmentCents({ quantity: 2, originalUnitPrice: 100, baseUnitPrice: 80, unitPrice: 85, priceType: 'PROMOCIONAL' }), { discount: 0, addition: 1000, promotion: 4000 });
assert.equal(addQuantity(0.1, 0.2), 0.3);
assert.equal(quantityAmount('0,001'), 0.001);
assert.equal(quantityAmount('1.234,567'), 1234.567);
for (const invalid of ['-1', '0.0001', 'Infinity', 'abc']) assert.ok(Number.isNaN(quantityAmount(invalid)));
assert.ok(Number.isNaN(saleLineCents(1e30, 1)));
assert.equal(saleSubtotal([{ unitPrice: 0.75, quantity: 2.9 }, { unitPrice: 0.01, quantity: 0.5 }]), 2.19);
console.log('APROVADO: HALF_UP por linha, milésimos, soma de quantidades e limites numéricos.');
assert.equal(saleReturnCents({ subtotal: '2.18', discount: 0, addition: 0, items: [{ subtotal: '2.18', quantity: 2.9 }] }, [{ itemIndex: 0, quantity: 2.9 }]), 218);
assert.equal(saleReturnCents({ subtotal: 3, discount: 2, addition: 0, items: [{ subtotal: 3, quantity: 3 }] }, [{ itemIndex: 0, quantity: 1.005 }]), 34);
