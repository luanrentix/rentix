const assert = require('node:assert/strict');
const fs = require('node:fs');
const ts = require('typescript');
const source = fs.readFileSync('services/cash-report.ts', 'utf8');
const compiled = ts.transpileModule(source, { compilerOptions: { module: ts.ModuleKind.CommonJS, target: ts.ScriptTarget.ES2020 } }).outputText;
const reportModule = { exports: {} };
new Function('module', 'exports', compiled)(reportModule, reportModule.exports);
const { buildCashReport } = reportModule.exports;
const base = { id: '1', date: '2026-11-05T12:00:00Z', direction: 'IN', amount: 0.1, method: 'CASH', kind: 'RECEBIMENTO', description: 'Venda', accountId: 'cash', accountName: 'Caixa', orderNumber: 1, customer: 'Cliente', operator: 'Operador' };
const filters = { start: '2026-11-01', end: '2026-11-05', method: '', account: '', search: '' };
const rows = Array.from({ length: 60 }, (_, i) => ({ ...base, id: String(i), orderNumber: i + 1, amount: i === 59 ? 0.3 : 0.1, direction: i === 59 ? 'OUT' : 'IN' }));
const html = buildCashReport(rows, filters, { tradeName: 'Empresa' });
assert.ok(html.includes('#60'), 'includes rows beyond the first page');
assert.ok(html.includes('60 movimentação(ões)'));
assert.ok(html.includes('5,90'));
assert.ok(html.includes('5,60'));
assert.ok(html.includes('01/11/2026 a 05/11/2026'));
assert.ok(html.includes('A4 landscape'));
assert.ok(html.includes('display:table-header-group'));
const unsafe = buildCashReport([{ ...base, customer: '<script>alert(1)</script>', description: '<img src=x onerror=alert(1)>' }], { ...filters, search: '<iframe>' }, { tradeName: '<script>' });
assert.ok(!unsafe.includes('<script>'));
assert.ok(!unsafe.includes('<img src=x'));
assert.ok(!unsafe.includes('<iframe>'));
assert.ok(unsafe.includes('&lt;script&gt;'));
assert.ok(buildCashReport([], filters).includes('Nenhuma movimentação'));
console.log('APROVADO: totais em centavos, filtros, todas as páginas, relatório vazio e escape de conteúdo.');
