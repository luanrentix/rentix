const assert = require('node:assert/strict');
const ts = require('typescript');
const fs = require('node:fs');
const moduleForTest = { exports: {} };
new Function('module', 'exports', ts.transpileModule(fs.readFileSync('services/sales-payment.ts', 'utf8'), { compilerOptions: { module: ts.ModuleKind.CommonJS } }).outputText)(moduleForTest, moduleForTest.exports);
const { paymentAmount, paymentBreakdown, installmentPreview, validateSalePayment } = moduleForTest.exports;
const empty = { DINHEIRO: '0,00', PIX: '0,00', DEBITO: '0,00', CREDITO: '0,00', CREDIARIO: '0,00', SALDO_CLIENTE: '0,00' };
const base = { method: 'DINHEIRO', parts: empty, total: 100, accountId: 'caixa', accounts: [{ id: 'caixa' }], customer: { isSystem: false, creditBlocked: false, creditDays: 30, creditLimit: 500 }, creditBalance: 100, installments: 3, tender: '' };
const reference = { ...base.customer, referenceOnly: true };
assert.equal(validateSalePayment({ ...base, customer: reference }), null);
assert.match(validateSalePayment({ ...base, method: 'CREDIARIO', customer: reference }), /apenas referência/);
assert.match(validateSalePayment({ ...base, method: 'MISTO', parts: { ...empty, DINHEIRO: '50,00', CREDIARIO: '50,00' }, customer: reference }), /apenas referência/);
for (const method of Object.keys(empty)) assert.equal(validateSalePayment({ ...base, method }), null, method);
assert.equal(paymentAmount('1.234,56'), 1234.56);
assert.equal(paymentAmount('12.50'), 12.5);
for (const value of ['-1', 'texto', '1,234', 'Infinity']) assert.ok(Number.isNaN(paymentAmount(value)), value);
assert.equal(validateSalePayment({ ...base, tender: '150,00' }), null);
assert.match(validateSalePayment({ ...base, tender: '99,99' }), /dinheiro entregue/);
assert.match(validateSalePayment({ ...base, accountId: '' }), /conta/);
assert.equal(validateSalePayment({ ...base, method: 'CREDIARIO', accountId: '' }), null);
assert.equal(validateSalePayment({ ...base, method: 'SALDO_CLIENTE', accountId: '' }), null);
assert.match(validateSalePayment({ ...base, method: 'SALDO_CLIENTE', creditBalance: 99.99 }), /saldo disponível/);
assert.match(validateSalePayment({ ...base, method: 'CREDIARIO', customer: { ...base.customer, isSystem: true } }), /identificado/);
assert.match(validateSalePayment({ ...base, method: 'CREDIARIO', customer: { ...base.customer, creditBlocked: true } }), /liberado/);
assert.match(validateSalePayment({ ...base, method: 'CREDIARIO', customer: { ...base.customer, creditDays: null } }), /prazo/);
assert.match(validateSalePayment({ ...base, method: 'CREDIARIO', installments: 0 }), /parcelas/);
assert.deepEqual(installmentPreview(100, 3), [33.34, 33.33, 33.33]);
assert.deepEqual(installmentPreview(0.01, 2), []);
const parts = { ...empty, DINHEIRO: '25,00', PIX: '25,00', CREDIARIO: '25,00', SALDO_CLIENTE: '25,00' };
assert.equal(validateSalePayment({ ...base, method: 'MISTO', parts }), null);
assert.equal(paymentBreakdown('MISTO', parts, 100).immediate, 50);
assert.match(validateSalePayment({ ...base, method: 'MISTO', parts: { ...parts, PIX: '24,99' } }), /Falta distribuir/);
assert.match(validateSalePayment({ ...base, method: 'MISTO', parts: { ...parts, PIX: '25,01' } }), /ultrapassam/);
assert.match(validateSalePayment({ ...base, method: 'MISTO', parts: { ...parts, PIX: 'abc' } }), /valores válidos/);
console.log('APROVADO: seis formas, misto, centavos, troco, conta, crediário, saldo e parcelas.');
